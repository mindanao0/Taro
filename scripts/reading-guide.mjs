const FRIEND = new Set(['air-fire', 'earth-water']), ENEMY = new Set(['fire-water', 'air-earth']);
export function relation(a, b) {
  if (a === b) return 'same';
  const k = [a, b].sort().join('-');
  return FRIEND.has(k) ? 'feed' : ENEMY.has(k) ? 'oppose' : 'neutral';
}

