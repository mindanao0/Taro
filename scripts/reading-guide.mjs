const fill = (t, v) => t.replace(/\{(\w+)\}/g, (_, k) => v[k]);

/** Position-specific lead sentence for one drawn card. */
export function frameFor(spreadId, positionId, card, orientation, meaning) {
  const p = POSITIONS[`${spreadId}:${positionId}`];
  if (!p) return meaning;
  return fill(orientation === 'reversed' ? p.rev : p.up, {n: card.name_en, m: meaning});
}

/** Readings for pairs of positions whose cards are both opened. drawn = [{position_id, card, orientation, i}] */
export function pairReadings(spreadId, drawn, isOpen = () => true) {
  const at = id => drawn.find(d => d.position_id === id);
  return (PAIRS[spreadId] || []).flatMap(role => {
    const a = at(role.at[0]), b = at(role.at[1]);
    if (!a || !b || !isOpen(a) || !isOpen(b)) return [];
    const ea = elementOf(a.card), eb = elementOf(b.card), rel = relation(ea, eb);
    let text = fill(role[rel], {A: a.card.name_en, B: b.card.name_en, ea: ELEMENT_TH[ea], eb: ELEMENT_TH[eb], e: ELEMENT_TH[ea]});
    if ((a.orientation === 'reversed') !== (b.orientation === 'reversed')) text += ' ' + role.mixed;
    return [{title: role.title, a, b, text}];
  });
}
